#!/usr/bin/env bash
# Build a signed Aurora Markets Android APK with the SDK command-line tools.
#
# No Gradle: this project is a single activity plus a WebView, so the four
# build steps (aapt2 compile/link -> javac -> d8 -> apksigner) are faster and
# easier to audit than a full Gradle build. Set ANDROID_HOME to your SDK and
# JAVA_HOME to a JDK 17+; everything else has a sane default.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ANDROID_HOME="${ANDROID_HOME:-/workspace/android-sdk}"
JAVA_HOME="${JAVA_HOME:-/usr/lib/jvm/java-21-openjdk-amd64}"
BT="$ANDROID_HOME/build-tools/34.0.0"
PLATFORM="$ANDROID_HOME/platforms/android-34/android.jar"
export PATH="$JAVA_HOME/bin:$PATH"

KS="$HERE/keystore/aurora.keystore"
KS_PASS="${KS_PASS:-aurora123}"
KS_ALIAS="${KS_ALIAS:-aurora}"

APP="$HERE/app"
BUILD="$HERE/build"
OUT="$HERE/../dist/AuroraMarkets.apk"

for f in "$BT/aapt2" "$BT/d8" "$BT/apksigner" "$BT/zipalign" "$PLATFORM"; do
  [ -e "$f" ] || { echo "missing: $f (set ANDROID_HOME / install build-tools;34.0.0 platforms;android-34)"; exit 1; }
done

rm -rf "$BUILD"
mkdir -p "$BUILD/res" "$BUILD/gen" "$BUILD/classes" "$BUILD/dex"
mkdir -p "$(dirname "$OUT")"

# Bake the server address into a generated BuildConfig if AURORA_SERVER is set.
# Empty (the default) makes the app ask the user for a server on first launch.
AURORA_SERVER="${AURORA_SERVER:-}"
mkdir -p "$BUILD/gen/com/aurora/markets"
cat > "$BUILD/gen/com/aurora/markets/BuildConfig.java" <<EOF
package com.aurora.markets;

/** Generated by android/build.sh. Do not edit. */
public final class BuildConfig {
    public static final String DEFAULT_SERVER = "$AURORA_SERVER";
    private BuildConfig() { }
}
EOF

echo "1/6 compiling resources"
"$BT/aapt2" compile --dir "$APP/res" -o "$BUILD/res.zip"

echo "2/6 linking resources + manifest"
"$BT/aapt2" link \
  -o "$BUILD/base.apk" \
  -I "$PLATFORM" \
  --manifest "$APP/AndroidManifest.xml" \
  --java "$BUILD/gen" \
  --min-sdk-version 21 \
  --target-sdk-version 34 \
  --version-code 1 --version-name 1.7.0 \
  --no-version-vectors \
  -R "$BUILD/res.zip" \
  --auto-add-overlay

echo "3/6 compiling java"
find "$APP/src" "$BUILD/gen" -name '*.java' > "$BUILD/sources.txt"
# Source/target 8 keeps the dex compatible with older runtimes, but javac then
# emits a synthetic accessor for cross-class package-private access, and the d8
# in this toolchain crashes on any InnerClasses/synthetic-access class. Top-level
# classes plus target 11 avoid that; d8 min-api 21 handles target 11 fine.
if ! javac -source 11 -target 11 -encoding UTF-8 \
      -classpath "$PLATFORM" \
      -d "$BUILD/classes" @"$BUILD/sources.txt" > "$BUILD/javac.log" 2>&1; then
  cat "$BUILD/javac.log"
  echo "javac failed"
  exit 1
fi

echo "4/6 dexing"
"$BT/d8" --min-api 21 --lib "$PLATFORM" --output "$BUILD/dex" \
  $(find "$BUILD/classes" -name '*.class')

echo "5/6 packaging"
cp "$BUILD/base.apk" "$BUILD/unsigned.apk"
( cd "$BUILD/dex" && zip -q -X "$BUILD/unsigned.apk" classes.dex )
"$BT/zipalign" -f -p 4 "$BUILD/unsigned.apk" "$BUILD/aligned.apk"

echo "6/6 signing"
"$BT/apksigner" sign \
  --ks "$KS" --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" \
  --ks-key-alias "$KS_ALIAS" \
  --min-sdk-version 21 \
  --out "$OUT" "$BUILD/aligned.apk"
"$BT/apksigner" verify --print-certs "$OUT" | head -3

echo
echo "APK: $OUT  ($(du -h "$OUT" | cut -f1))"
